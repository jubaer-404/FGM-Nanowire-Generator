import { FGMBuildResult } from './types';

/**
 * Generates the LAMMPS data file string
 */
export function generateLAMMPSData(result: FGMBuildResult, maxAtoms?: number): string {
  const { box, atoms, config } = result;
  const numAtoms = atoms.length;
  const atomsToPrint = maxAtoms ? atoms.slice(0, maxAtoms) : atoms;

  // Atom types count = number of base segments + 1 graded material
  const numTypes = config.baseSegments.length + 1;

  let text = `LAMMPS data file of Multi-Material FGM Nanostructure generated by FGM Generator\n\n`;
  text += `\t\t${numAtoms} atoms\n`;
  text += `\t\t${numTypes} atom types\n`;

  // Simulation box bounds
  text += `\t${box.x[0].toFixed(8)} ${box.x[1].toFixed(8)} \txlo xhi\n`;
  text += `\t${box.y[0].toFixed(8)} ${box.y[1].toFixed(8)} \tylo yhi\n`;
  text += `\t${box.z[0].toFixed(8)} ${box.z[1].toFixed(8)} \tzlo zhi\n\n`;

  // Masses
  text += `Masses\n\n`;
  for (let idx = 0; idx < config.baseSegments.length; idx++) {
    const seg = config.baseSegments[idx];
    const segTypeId = idx + 1;
    text += `\t\t${segTypeId} ${seg.mass.toFixed(6)} \t# ${seg.symbol} (${seg.name} Base)\n`;
  }
  const gradedTypeId = config.baseSegments.length + 1;
  text += `\t\t${gradedTypeId} ${config.gradedMaterial.mass.toFixed(6)} \t# ${config.gradedMaterial.symbol} (${config.gradedMaterial.name} Graded)\n\n`;

  // Atoms
  text += `Atoms\n\n`;
  for (const a of atomsToPrint) {
    text += `${a.id} ${a.type} ${a.x.toFixed(6)} ${a.y.toFixed(6)} ${a.z.toFixed(6)}\n`;
  }

  if (maxAtoms && atoms.length > maxAtoms) {
    text += `# ... [Preview truncated to first ${maxAtoms} atoms. Download full file to get all ${atoms.length} atoms] ...\n`;
  }

  return text;
}

/**
 * Generates standard XYZ coordinate file format for OVITO / VESTA / PyMOL
 */
export function generateXYZData(result: FGMBuildResult): string {
  const { atoms, config } = result;
  let text = `${atoms.length}\n`;
  text += `Multi-Material FGM Nanostructure: Base=[${config.baseSegments.map((s) => s.symbol).join('-')}] Graded=${config.gradedMaterial.symbol} (${config.gradingKind}-FGM)\n`;

  for (const a of atoms) {
    text += `${a.symbol} ${a.x.toFixed(6)} ${a.y.toFixed(6)} ${a.z.toFixed(6)}\n`;
  }
  return text;
}

/**
 * Generates a ready-to-run LAMMPS simulation script (in.fgm)
 */
export function generateLAMMPSScript(result: FGMBuildResult, dataFileName = 'structure.data'): string {
  const { config } = result;
  const elements = [
    ...config.baseSegments.map((s) => s.symbol),
    config.gradedMaterial.symbol,
  ];

  return `# -------------------------------------------------------------
# LAMMPS Input Script: Multi-Material FGM Nanostructure Simulation
# Base: ${config.baseSegments.map((s) => `${s.symbol} (${s.length_nm}nm)`).join(' + ')}
# Graded: ${config.gradedMaterial.symbol} via ${config.gradingKind.toUpperCase()}-FGM
# -------------------------------------------------------------

# 1. Initialization
units           metal
dimension       3
boundary        p p p
atom_style      atomic

# 2. Structure setup
read_data       ${dataFileName}

# 3. Interatomic Potential Setup
# Note: Choose an appropriate EAM/FS or MEAM/ADP alloy potential for: ${elements.join(' ')}
# e.g., pair_style eam/alloy
# pair_coeff * * ${elements.join('_')}.eam.alloy ${elements.join(' ')}
# (Placeholder LJ potential shown below for initial testing):
pair_style      lj/cut 6.0
pair_coeff      * * 0.1 2.5

# 4. Energy Minimization (Equilibration of interfaces)
thermo          50
thermo_style    custom step temp pe etotal press lx ly lz
dump            1 all custom 100 dump.minimization.lammpstrj id type x y z
min_style       cg
minimize        1.0e-6 1.0e-8 5000 10000
undump          1

# 5. Thermal Equilibration (NPT @ 300K)
reset_timestep  0
velocity        all create 300.0 4928459 mom yes rot yes dist gaussian
fix             1 all npt temp 300.0 300.0 0.1 iso 0.0 0.0 1.0
timestep        0.001
dump            2 all custom 500 dump.equil.lammpstrj id type x y z
run             10000
unfix           1
undump          2

# 6. Uniaxial Tensile Deformation (along z-axis)
variable        srate equal 1.0e9
variable        srate1 equal "v_srate / 1.0e12"
fix             2 all deform 1 z erate \${srate1} remap x
fix             3 all npt temp 300.0 300.0 0.1 x 0.0 0.0 1.0 y 0.0 0.0 1.0

variable        strain equal "(lz - v_L0)/v_L0"
variable        p1 equal "-pzz/10000" # Stress in GPa
fix             def all print 100 "\${strain} \${p1}" file stress_strain.dat screen no title "Strain Stress_GPa"

dump            3 all custom 1000 dump.tensile.lammpstrj id type x y z
run             50000
`;
}

/**
 * Generates CSV string of bin compositions
 */
export function generateBinCSV(result: FGMBuildResult): string {
  const { bins, config } = result;
  const baseHeaders = config.baseSegments.map((s) => `${s.symbol}_count`).join(',');

  let csv = `Bin,Normalized_Pos_b,Lo_A,Hi_A,Total_Atoms,Graded_Atoms,Target_Fraction,Actual_Atom_Frac,Actual_Mass_Frac,${baseHeaders}\n`;

  for (const bi of bins) {
    const baseCounts = config.baseSegments
      .map((s) => bi.baseAtomsCount[s.type_id] || 0)
      .join(',');

    csv += `${bi.bin},${bi.b.toFixed(4)},${bi.lo.toFixed(2)},${bi.hi.toFixed(2)},${bi.totalAtoms},${bi.gradedAtoms},${bi.targetGradingFraction.toFixed(4)},${bi.actualAtomFraction.toFixed(4)},${bi.actualMassFraction.toFixed(4)},${baseCounts}\n`;
  }

  return csv;
}
